function vkReadDataUrl(file) {
    return new Promise((res, rej) => { const r = new FileReader(); r.onload = () => res(r.result); r.onerror = rej; r.readAsDataURL(file); });
}
function vkCompress(file, maxSize, quality) {
    return new Promise((res, rej) => {
        const r = new FileReader();
        r.onerror = rej;
        r.onload = () => {
            const img = new Image();
            img.onerror = () => rej(new Error('image'));
            img.onload = () => {
                const k = Math.min(1, maxSize / Math.max(img.width, img.height));
                const c = document.createElement('canvas');
                c.width = Math.max(1, Math.round(img.width * k));
                c.height = Math.max(1, Math.round(img.height * k));
                const x = c.getContext('2d');
                x.fillStyle = '#fff'; x.fillRect(0, 0, c.width, c.height);
                x.drawImage(img, 0, 0, c.width, c.height);
                res(c.toDataURL('image/jpeg', quality));
            };
            img.src = r.result;
        };
        r.readAsDataURL(file);
    });
}
async function vkAddFiles(list) {
    for (const f of Array.from(list)) {
        if (vkFiles.length >= VK_MAX_FILES) { showToast('সর্বোচ্চ ' + vkBn(VK_MAX_FILES) + 'টি ফাইল যুক্ত করা যাবে।', 'error'); break; }
        try {
            if (f.type.startsWith('image/')) {
                vkFiles.push({ name: f.name, type: 'image/jpeg', data: await vkCompress(f, 1000, 0.72) });
            } else if (f.type === 'application/pdf') {
                if (f.size > 700 * 1024) { showToast('PDF ফাইল ৭০০ KB-এর বেশি হতে পারবে না।', 'error'); continue; }
                vkFiles.push({ name: f.name, type: 'application/pdf', data: await vkReadDataUrl(f) });
            } else {
                showToast('শুধু ছবি (JPG/PNG/WebP) বা PDF দেওয়া যাবে।', 'error');
            }
        } catch (err) {
            showToast('"' + f.name + '" পড়া যায়নি — অন্য ফরম্যাটের ছবি (JPG/PNG) চেষ্টা করুন।', 'error');
        }
    }
    vkRenderPrev();
}
function vkWireUpload() {
    const drop = document.getElementById('vk-drop');
    const inp = document.getElementById('vk-file-input');
    if (!drop || !inp) return;
    inp.addEventListener('change', () => { vkAddFiles(inp.files).then(() => { inp.value = ''; }); });
    ['dragenter', 'dragover'].forEach(ev => drop.addEventListener(ev, e => { e.preventDefault(); drop.classList.add('drag'); }));
    ['dragleave', 'drop'].forEach(ev => drop.addEventListener(ev, e => { e.preventDefault(); drop.classList.remove('drag'); }));
    drop.addEventListener('drop', e => { if (e.dataTransfer && e.dataTransfer.files) vkAddFiles(e.dataTransfer.files); });
    drop.addEventListener('keydown', e => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); inp.click(); } });
}

