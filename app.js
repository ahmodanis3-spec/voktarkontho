        function handleFormSubmit(e) {
            e.preventDefault();

            const proofUrl = document.getElementById('form-proof-url').value.trim();
            const files = (typeof vkGetFiles === 'function') ? vkGetFiles() : [];

            // Mandatory Proof Validation: লিংক অথবা আপলোড করা ফাইল — যেকোনো একটি
            if (!proofUrl && files.length === 0) {
                showToast("প্রমাণের লিংক দিন অথবা ছবি/ফাইল আপলোড করুন — প্রমাণ বাধ্যতামূলক!", "error");
                return;
            }

            const identityType = document.querySelector('input[name="identity_type"]:checked').value;
            const division = document.getElementById('form-division').value;
            const district = document.getElementById('form-district').value;
            const upazila = document.getElementById('form-upazila').value;
            const union = document.getElementById('form-union').value;
            const spot = document.getElementById('form-spot').value;
            const target = document.getElementById('form-target').value;
            const title = document.getElementById('form-title').value;
            const description = document.getElementById('form-description').value;
            const catEl = document.getElementById('form-category');
            const category = (catEl && catEl.value) || vkInferCategory(title + ' ' + description + ' ' + target);

            const userName = identityType === 'named' ? document.getElementById('form-user-name').value : '';
            const userContact = identityType === 'named' ? document.getElementById('form-user-contact').value : '';

            let newId;
            do { newId = "CMP-" + Math.floor(1000 + Math.random() * 9000); }
            while (complaints.some(c => c.id === newId));

            const newComplaint = {
                id: newId,
                division,
                district,
                upazila,
                union,
                spot,
                target,
                title,
                description,
                proofUrl,
                proofFiles: files,
                category,
                identityType,
                userName,
                userContact,
                status: "Pending", // New complaints are pending admin review
                upvotes: 1,
                createdAt: new Date().toISOString().split('T')[0]
            };

            // নিজের অভিযোগে আলাদা করে আর সমর্থন দেওয়া যাবে না (১ ভোট আগেই গোনা হয়েছে)
            const sup = vkSupportedSet(); sup.add(newId); vkSaveSupported(sup);

            complaints.unshift(newComplaint);
            saveComplaints(true);

            // স্টোরেজ ভরে গেলে: ফাইল বাদ দিয়ে আবার চেষ্টা (লিংক থাকলে), নইলে অভিযোগ বাতিল
            if (window.vkSaveFailed && files.length) {
                if (proofUrl) {
                    newComplaint.proofFiles = [];
                    saveComplaints(true);
                    showToast("স্টোরেজ ভরে যাওয়ায় ফাইল সংযুক্ত করা যায়নি; লিংকসহ অভিযোগ জমা হয়েছে।", "error");
                } else {
                    complaints.shift();
                    saveComplaints(true);
                    showToast("ডিভাইসের স্টোরেজ ভরা — ছবি ছোট করে বা প্রমাণের লিংক দিয়ে আবার চেষ্টা করুন।", "error");
                    return;
                }
            }

            // Reset Form
            document.getElementById('submitForm').reset();
            document.getElementById('form-district').disabled = true;
            document.getElementById('form-upazila').disabled = true;
            toggleIdentityFields(false);
            if (typeof vkResetUploads === 'function') vkResetUploads();

            showToast("অভিযোগটি জমা হয়েছে! অ্যাডমিন যাচাই করার পর সম্পূর্ণ ভেরিফাইড ব্যাজ দেখাবে।", "success");
        }

