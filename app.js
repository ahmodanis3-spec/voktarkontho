function vkFmtDate(d) {
    const dt = d ? new Date(String(d).length <= 10 ? d + 'T00:00:00' : d) : new Date();
    if (isNaN(dt)) return d || '';
    return dt.toLocaleDateString('bn-BD', { year: 'numeric', month: 'long', day: 'numeric' });
}
