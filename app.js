        function applyFilters() {
            const keyword = document.getElementById('search-keyword').value.toLowerCase();
            const div = document.getElementById('filter-division').value;
            const dist = document.getElementById('filter-district').value;
            const upz = document.getElementById('filter-upazila').value;
            const status = document.getElementById('filter-status').value;
            const area = window.vkArea || '';
            const cat = window.vkCat || '';

            const filtered = complaints.filter(c => {
                const matchesKey = !keyword ||
                    c.target.toLowerCase().includes(keyword) ||
                    c.spot.toLowerCase().includes(keyword) ||
                    c.title.toLowerCase().includes(keyword) ||
                    c.description.toLowerCase().includes(keyword);

                const matchesDiv = !div || c.division === div;
                const matchesDist = !dist || c.district === dist;
                const matchesUpz = !upz || c.upazila === upz;
                const matchesStatus = !status || c.status === status;
                const matchesArea = vkInArea(c, area);
                const matchesCat = !cat || vkCategoryOf(c) === cat;

                return matchesKey && matchesDiv && matchesDist && matchesUpz && matchesStatus && matchesArea && matchesCat;
            });

            renderFeed(filtered);
        }

